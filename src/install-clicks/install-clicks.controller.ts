import { Controller, Get, Headers, Ip, Param, Redirect } from '@nestjs/common';
import { ApiFoundResponse, ApiNotFoundResponse, ApiOperation, ApiParam, ApiTags } from '@nestjs/swagger';
import { Public } from '../auth/public.decorator';
import { InstallClicksService } from './install-clicks.service';

@ApiTags('install-clicks')
@Controller('i')
export class InstallClicksController {
  constructor(private readonly service: InstallClicksService) {}

  @Public()
  @Get(':token')
  @Redirect()
  @ApiOperation({
    summary: 'Public install click endpoint',
    description: 'Public endpoint (no API key required). Validates token, creates install_click_id, saves install_click metadata, builds destination URL with ayanco_install_click_id and ayanco_token, and redirects the user to app store URL.',
  })
  @ApiParam({ name: 'token', example: 'gzb1405', description: 'Install link token generated by POST /api/v1/install-links' })
  @ApiFoundResponse({ description: 'Redirects user to destination store URL with ayanco_token, ayanco_install_click_id, utm_source, and utm_campaign.' })
  @ApiNotFoundResponse({ schema: { example: { success: false, error_code: 'INSTALL_LINK_NOT_FOUND', message: 'Install link token was not found or is inactive' } } })
  async click(@Param('token') token: string, @Ip() ip: string, @Headers('user-agent') userAgent?: string) {
    const result = await this.service.processClick(token, ip, userAgent);
    return { url: result.redirectUrl, statusCode: 302 };
  }
}
